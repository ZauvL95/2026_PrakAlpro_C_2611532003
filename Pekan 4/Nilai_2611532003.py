# Buat program nested if
# Nama variable ditambah 4 digit nim terakhir contoh: ipk_1234
# Program ini menggunakan fungsi input()
# Program konversi  nilai angka menjadi huruf

nilai_2003 = int(input("Inputkan nilai angka: "))

if nilai_2003 >= 81:
    print('A')
elif nilai_2003 >= 70:
    print('B')
elif nilai_2003 >= 60:
    print('C')
elif nilai_2003 >= 50:
    print('D')
else:
    print('E')